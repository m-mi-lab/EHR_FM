# Regenerate figures/clean_benchmark_table.tex from the rebuilt pipeline. Clean AUROC + 95% CI come from the
# dose-0 cell of each model's true-removal sweep, <task>.event.json (2,000-resample patient bootstrap on the whole held-out split);
# models whose sweep has not run yet show the finetune's held-out AUROC without an interval; models whose
# finetune has not run show a dash.
import json, os
fam = [("BiLSTM", [("bilstms", 10.3), ("bilstm", 20.2), ("bilstml", 33.2)]),
       ("BERT", [("berts", 29.2), ("bert", 91.1), ("bertl", 310.4)]),
       ("BigBird", [("bigbird", 94.8)]),
       ("GPT-2", [("gpt2s", 91.1), ("gpt2", 310.4), ("gpt2l", 718.4)]),
       ("Mistral", [("mistrals", 34.4), ("mistral", 108.7)]),
       ("Mamba", [("mambas", 31.1), ("mamba", 96.6), ("mambal", 328.1)])]
tasks = ["mortality", "los_gt_7d", "readmit_30d"]
def cell(m, t):
    f = f"data/results/missingness/{m}/{t}.event.json"
    if os.path.exists(f):
        r = [c for c in json.load(open(f)) if c["frac"] == 0 and c["family"] == "A1" and c["protocol"] == "event"][0]
        return f"{r['auroc']:.3f}\\,\\tiny{{[{r['ci_lo']:.3f},{r['ci_hi']:.3f}]}}"
    f = f"data/models/{m}_ft/{t}/result.json"
    if os.path.exists(f): return f"{json.load(open(f))['test_auroc']:.3f}\\textsuperscript{{p}}"
    return "---"
lines = [r"% Auto-generated by scripts/build_clean_table.py (rebuilt pipeline, 2026-10-08) -- clean-benchmark AUROC.",
r"\begin{table}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{5pt}",
r"\caption{Clean-benchmark held-out AUROC on fully observed MIMIC-IV, by architecture family and parameter count. Every model reads the same token stream; the window is $512$ tokens for the BiLSTM and BERT families, $1{,}024$ for GPT-2, $2{,}048$ for Mistral and Mamba and $4{,}096$ for BigBird. On every task the finetuned models sit within $0.02$ AUROC of each other ($0.93$--$0.94$ mortality, $0.83$--$0.85$ length of stay, $0.77$--$0.79$ readmission), and parameter count induces no consistent ordering: the largest BiLSTM and BERT are their families' best, while the medium GPT-2 and Mistral are not. $95\%$ patient-level bootstrap intervals ($2{,}000$ resamples of the held-out split) are shown. \textsuperscript{p}~finetune finished, missingness sweep (and therefore the interval) pending; --- finetune pending (pretraining still running on 2026-10-08).}",
r"\label{tab:clean}", r"\begin{tabular}{llccc}", r"\toprule",
r"Family & Params (M) & Mortality & LOS $>7$d & Readmission \\", r"\midrule"]
for name, members in fam:
    for i, (m, p) in enumerate(members):
        lines.append(f"{name if i == 0 else ''} & {p:g} & " + " & ".join(cell(m, t) for t in tasks) + r" \\")
    lines.append(r"\addlinespace[1pt]")
lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
print("\n".join(lines))
